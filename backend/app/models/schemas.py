class InterviewEvaluateRequest(BaseModel):
    """Request payload to evaluate a candidate's answer to an interview question."""
    question: str = Field(..., min_length=5, description="The interview question being answered")
    category: Literal["technical", "resume", "behavioral", "job-specific"] = Field(
        "technical", description="Question category"
    )
    answer: str = Field(..., min_length=10, max_length=10000, description="The candidate's response text")
    job_description: Optional[str] = Field(None, description="Target job description context")
    resume_context: Optional[str] = Field(None, description="Candidate resume context")


class InterviewEvaluationSchema(BaseModel):
    """Structured evaluation feedback generated by Amazon Bedrock for an interview answer."""
    overall_score: int = Field(..., ge=0, le=10, description="Overall score from 0 to 10")
    relevance_score: int = Field(..., ge=0, le=10, description="How well the answer addressed the specific question (0-10)")
    technical_score: int = Field(..., ge=0, le=10, description="Technical depth, accuracy, or framework adherence (0-10)")
    clarity_score: int = Field(..., ge=0, le=10, description="Structure, communication clarity, and conciseness (0-10)")
    completeness_score: int = Field(..., ge=0, le=10, description="Coverage of critical concepts and examples (0-10)")
    strengths: List[str] = Field(default_factory=list, description="What the candidate did well in the answer")
    missing_points: List[str] = Field(default_factory=list, description="Key concepts or details that were missing")
    improvement_tips: List[str] = Field(default_factory=list, description="Actionable advice on how to improve this answer")
    suggested_better_answer: str = Field(..., description="An exemplary model answer demonstrating best practices")
    final_feedback: str = Field(..., description="Summary coaching feedback and encouragement")


class InterviewEvaluateResponse(BaseModel):
    """Response returned by the interview evaluation endpoint."""
    success: bool = True
    message: str = "Answer evaluated successfully."
    mode: Literal["bedrock_ai", "mock_preview"] = Field(
        "bedrock_ai", description="Mode indicating live Bedrock AI or preview fallback"
    )
    model_id: Optional[str] = Field(None, description="Amazon Bedrock model ID used for evaluation")
    evaluation: InterviewEvaluationSchema


class ErrorResponse(BaseModel):
    """Standard error response."""
    success: bool = False
    error: str = Field(..., description="User-friendly error summary")
    detail: Optional[str] = Field(None, description="Optional extra detail or guidance")
